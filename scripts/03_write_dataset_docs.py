#!/usr/bin/env python3
"""Generate outputs/DATASETS.md from recorded facts (manifest + probe + inventory).

Every number in the report comes from files on disk or from a recorded HTTP result;
nothing is copied from a paper or a dataset card.

Run: .venv/bin/python scripts/03_write_dataset_docs.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.data import registry
from src.utils.paths import INTERIM, OUT, RAW, REPORTS, ensure_dirs

OUT_MD = OUT / "DATASETS.md"


def human(n: float | None) -> str:
    if not n:
        return "-"
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.1f} {unit}"
        n /= 1024
    return f"{n:.1f} GB"


def load(path: Path) -> dict:
    return json.loads(path.read_text()) if path.exists() else {}


def main() -> int:
    ensure_dirs()
    manifest = load(RAW / "MANIFEST.json")
    probe = load(REPORTS / "network_probe.json")
    inv = load(INTERIM / "raw_inventory.json")

    official_probe = manifest.get("official_probe", [])
    mirrors = {m["key"]: m for m in manifest.get("mirrors", []) if m.get("ok")}
    mirror_spec = {m["key"]: m for m in registry.MIRRORS}
    inv_ds = inv.get("datasets", {})

    L: list[str] = []
    A = L.append
    A("# DATASETS.md - what was acquired, from where, under which licence\n")
    A("_Auto-generated by `scripts/03_write_dataset_docs.py`. Re-run after any download._\n")
    A(f"Manifest: `data/raw/MANIFEST.json` (generated {manifest.get('generated_at', 'n/a')})\n")

    # ---------------- 1. network reality ---------------- #
    A("\n## 1. Network reachability (measured, not assumed)\n")
    A("| host | reachable | detail |\n|---|---|---|")
    for r in probe.get("results", []):
        detail = "ok" if r["ok"] else (r.get("error") or "")[:58].replace("|", "/")
        A(f"| `{r['host']}` | {'yes' if r['ok'] else '**no**'} | {detail} |")

    # ---------------- 2. per-item status ---------------- #
    A("\n## 2. Spec section 3 items: status\n")
    A("| # | item | role (spec) | status | what we actually have |")
    A("|---|---|---|---|---|")
    status_map = {}
    for i, entry in enumerate(registry.OFFICIAL, 1):
        key = entry["key"]
        urls = [p for p in official_probe if p["key"] == key]
        official_ok = any(u["ok"] for u in urls)
        content_ok = bool(entry.get("content_available"))
        mirror = mirrors.get(key) or mirrors.get({"kaggle_large_scale_fish": "kaggle_large_scale_fish"}.get(key, ""))
        sub = [m for m in mirrors.values() if m.get("substitute_for") == key]
        if content_ok and official_ok:
            status, have = "official download OK", "official files"
        elif content_ok and mirror and mirror.get("identical_to_official"):
            status, have = "official host blocked -> verified copy", f"`data/raw/{key}`"
        elif not content_ok and official_ok:
            status, have = "host reachable, **no data in it** -> substitute", \
                f"`data/raw/{sub[0]['key']}` (not the official dataset)" if sub else "nothing"
        elif mirror and mirror.get("identical_to_official"):
            status, have = "official blocked -> verified copy", f"`data/raw/{key}`"
        elif sub:
            status, have = "official blocked -> **substitute**", f"`data/raw/{sub[0]['key']}` (not the official dataset)"
        elif key == "fishbase_india":
            status, have = "official blocked", "FishDex (FishBase-derived) for names/family only"
        elif key == "jh_fish":
            status, have = "not collected", "nothing"
        else:
            status, have = "**unavailable**", "nothing"
        status_map[key] = status
        A(f"| {i} | {entry['name']} | {entry['spec_use']} | {status} | {have} |")

    # ---------------- 3. acquired mirrors ---------------- #
    A("\n## 3. Files acquired (pinned commits, checksummed)\n")
    A("| dataset key | repo | commit | archive | extracted | licence | identical to official? |")
    A("|---|---|---|---|---|---|---|")
    for key, m in mirrors.items():
        A(f"| `{key}` | `{m['repo']}` | `{str(m.get('commit'))[:10]}` | "
          f"{human(m.get('bytes'))} | {m.get('extracted_files', '?')} files | "
          f"{m['licence'][:60]} | {'yes' if m.get('identical_to_official') else '**no (substitute for ' + str(m.get('substitute_for')) + ')**'} |")

    # ---------------- 4. measured contents ---------------- #
    A("\n## 4. Measured contents (counted from disk, not from papers)\n")
    A("| dataset key | layout | images | classes | unreadable | bytes |")
    A("|---|---|---|---|---|---|")
    for key, d in inv_ds.items():
        A(f"| `{key}` | {d.get('type')} | {d.get('n_images')} | "
          f"{d.get('n_classes') or d.get('n_classes_in_labels')} | {d.get('n_unreadable')} | "
          f"{human(d.get('bytes'))} |")

    for key, d in inv_ds.items():
        if d.get("type") == "classification" and d.get("classes"):
            A(f"\n<details><summary>class counts - `{key}`</summary>\n")
            A("| class folder | images |\n|---|---|")
            for c, n in sorted(d["classes"].items(), key=lambda x: -x[1]):
                A(f"| `{c}` | {n} |")
            A("\n</details>")
        if d.get("type") == "detection":
            A(f"\n### Detection layout - `{key}`\n")
            A(f"- images: {d.get('n_images')} | label files: {d.get('n_label_txt')} | "
              f"YOLO class ids present: {d.get('n_classes_in_labels')}")
            A(f"- images without a YOLO label: {d.get('n_images_without_yolo_label')} | "
              f"labels without an image: {d.get('n_yolo_labels_without_image')}")
            A(f"- class-id histogram: `{d.get('yolo_class_id_histogram')}`")
            A("- all class ids are collapsed to the single class `fish` for detector training (spec 6).")

    # ---------------- 5. licences & attribution ---------------- #
    A("\n## 5. Licence notes and attribution\n")
    for key, m in mirrors.items():
        spec = mirror_spec.get(key, {})
        A(f"### `{key}` - {m['repo']}\n")
        A(f"- licence: {m['licence']}")
        A(f"- provenance: {spec.get('provenance', m.get('provenance', 'n/a'))}")
        if spec.get("notes"):
            A(f"- usage note: {spec['notes']}")
        A("")

    A("\n## 6. Items that could not be obtained (no substitute invented)\n")
    for u in registry.UNAVAILABLE:
        A(f"- **{u['key']}**: {u['reason']}")

    A("\n## 7. Consequence for the project (read before reading any metric)\n")
    A("- Detector numbers come from a **substitute** detection set, not DePondFi.")
    A("- The 8-species Indian market dataset and the 48-species Assam dataset are **missing**; "
      "Indian species coverage is therefore reported against what is actually on disk, and the "
      "FishBase India checklist could not be pulled, so coverage-vs-FishBase-India is reported "
      "as **not computable**, not estimated.")
    A("- The label audit (spec 4.2) is applied to every dataset present; the specific 8-folder "
      "Seafood audit is documented as a plan with its per-folder verdicts marked *pending imagery*.")
    A("\nSee `outputs/DECISIONS.md` for the reasoning behind each fallback.")

    header_note = "<!-- generated -->\n"
    OUT_MD.write_text(header_note + "\n".join(L) + "\n")
    print(f"wrote {OUT_MD} ({len(L)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
